def read_text(dossier: str, name: str) -> str | None:
    for candidate in (os.path.join(dossier, "work", name), os.path.join(dossier, name)):
        if os.path.isfile(candidate):
            with open(candidate, encoding="utf-8") as f:
                return f.read()
    return None


def read_json(path: str) -> dict | None:
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def split_title(md: str) -> tuple[str | None, str]:
    lines = md.replace("\r\n", "\n").split("\n")
    for idx, line in enumerate(lines):
        if not line.strip():
            continue
        h = HEADING_RE.match(line)
        if h and len(h.group(1)) == 1:
            return h.group(2), "\n".join(lines[idx + 1:])
        break
    return None, md


def parse_readme(md: str) -> dict:
    title, body = split_title(md)
    verdict = None
    name = title or ""
    if title:
        m = re.search(r"(GO|VALIDATE-FIRST|PIVOT|KILL)\b", title)
        if m:
            verdict = m.group(1)
        name = re.split(r"\s+[—–-]+\s+Verdict", title)[0].strip()
        name = re.sub(r"\s*[—–-]?\s*Verdict:.*$", "", name).strip() or title
    lines = body.split("\n")
    meta: list[str] = []
    quote: list[str] = []
    rest_start = 0
    idx = 0
    while idx < len(lines) and not lines[idx].strip():
        idx += 1
    if idx < len(lines) and "·" in lines[idx] and not HEADING_RE.match(lines[idx]) and not QUOTE_RE.match(lines[idx]):
        meta = [m.strip() for m in lines[idx].split("·") if m.strip()]
        idx += 1
    while idx < len(lines) and not lines[idx].strip():
        idx += 1
    while idx < len(lines) and QUOTE_RE.match(lines[idx]):
        quote.append(QUOTE_RE.match(lines[idx]).group(1))
        idx += 1
    rest_start = idx
    return {
        "name": name,
        "verdict": verdict,
        "meta": meta,
        "quote": "\n".join(quote).strip(),
        "body": "\n".join(lines[rest_start:]),
    }


