def svg_text(x: float, y: float, s: str, cls: str, anchor: str = "start") -> str:
    return f'<text x="{x:.1f}" y="{y:.1f}" class="{cls}" text-anchor="{anchor}">{esc(s)}</text>'


def line_chart(cid: str, series: list[dict], horizon: int, cur: str | None, L: dict, lang: str,
               ref: tuple[float, str] | None = None) -> str:
    W, H = 640, 300
    PL, PR, PT, PB = 60, 92, 14, 34
    all_vals = [v for s in series for v in s["values"] if v is not None]
    lo, hi = min(0.0, min(all_vals)), max(all_vals)
    if ref and ref[0] is not None and ref[0] < hi * 3:
        hi = max(hi, ref[0])
    ticks = nice_ticks(lo, hi)
    lo, hi = ticks[0], ticks[-1]

    def x(m: float) -> float:
        return PL + (m - 1) / max(1, horizon - 1) * (W - PL - PR)

    def y(v: float) -> float:
        return PT + (hi - v) / (hi - lo) * (H - PT - PB)

    parts = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-labelledby="{cid}-t">']
    parts.append(f'<title id="{cid}-t">{esc(L["chart_users"] if "users" in cid else L["chart_cash"])}</title>')
    for t in ticks:
        parts.append(f'<line x1="{PL}" x2="{W - PR}" y1="{y(t):.1f}" y2="{y(t):.1f}" class="grid"/>')
        parts.append(svg_text(PL - 8, y(t) + 4, fmt_compact(t, cur), "axis", "end"))
    step = 6 if horizon > 24 else 3
    for m in range(1, horizon + 1):
        if m == 1 or m % step == 0:
            parts.append(svg_text(x(m), H - PB + 18, f"m{m}", "axis", "middle"))
    if lo < 0 < hi:
        parts.append(f'<line x1="{PL}" x2="{W - PR}" y1="{y(0):.1f}" y2="{y(0):.1f}" class="zero"/>')
    else:
        parts.append(f'<line x1="{PL}" x2="{W - PR}" y1="{y(lo):.1f}" y2="{y(lo):.1f}" class="baseline"/>')
    if ref and ref[0] is not None and lo <= ref[0] <= hi:
        parts.append(f'<line x1="{PL}" x2="{W - PR}" y1="{y(ref[0]):.1f}" y2="{y(ref[0]):.1f}" class="ref"/>')
        parts.append(svg_text(PL + 6, y(ref[0]) - 6, f"{ref[1]} · {fmt_num(round(ref[0]), lang)}", "ref-label"))
    labels = []
    for s in series:
        pts = " ".join(f"{x(i + 1):.1f},{y(v):.1f}" for i, v in enumerate(s["values"]) if v is not None)
        parts.append(f'<polyline points="{pts}" class="series s{s["slot"]}"/>')
        last = next((v for v in reversed(s["values"]) if v is not None), None)
        if last is not None:
            labels.append([y(last), s["label"], s["slot"]])
    labels.sort(key=lambda r: r[0])
    for k in range(1, len(labels)):
        if labels[k][0] - labels[k - 1][0] < 13:
            labels[k][0] = labels[k - 1][0] + 13
    for ly, label, slot in labels:
        parts.append(f'<circle cx="{W - PR:.1f}" cy="{ly:.1f}" r="3" class="dot s{slot}"/>')
        parts.append(svg_text(W - PR + 8, ly + 4, label, "end-label"))
    parts.append(f'<line class="xhair" x1="0" x2="0" y1="{PT}" y2="{H - PB}" hidden/>')
    parts.append(f'<rect class="hit" x="{PL}" y="{PT}" width="{W - PL - PR}" height="{H - PT - PB}"/>')
    parts.append("</svg>")
    data = {
        "x0": PL, "x1": W - PR, "w": W, "horizon": horizon, "cur": cur or "",
        "lang": lang,
        "series": [{"label": s["label"], "slot": s["slot"], "values": [None if v is None else round(v, 2) for v in s["values"]]} for s in series],
    }
    legend = "".join(f'<span class="lg"><i class="sw s{s["slot"]}"></i>{esc(s["label"])}</span>' for s in series)
    return (
        f'<figure class="chart line" id="{cid}" data-kind="line" data-chart=\'{esc(json.dumps(data)).replace(chr(39), "&#39;")}\'>'
        f'<div class="legend">{legend}</div>{"".join(parts)}<div class="tip" hidden></div></figure>'
    )


def checkpoint_table(series: list[dict], horizon: int, cur: str | None, lang: str, L: dict) -> str:
    months = [m for m in (3, 6, 12, 18, 24, 30, 36, 48, 60) if m <= horizon]
    if horizon not in months:
        months.append(horizon)
    out = ['<details class="table-view"><summary>', esc(L["table"]), "</summary>",
           '<div class="table-wrap"><table><thead><tr><th></th>']
    out += [f'<th class="al-right">m{m}</th>' for m in months]
    out.append("</tr></thead><tbody>")
    for s in series:
        out.append(f"<tr><td>{esc(s['label'])}</td>")
        for m in months:
            v = s["values"][m - 1] if m - 1 < len(s["values"]) else None
            out.append(f'<td class="al-right">{fmt_money(v, cur, lang) if cur else fmt_num(v, lang)}</td>')
        out.append("</tr>")
    out.append("</tbody></table></div></details>")
    return "".join(out)


def tornado(sens: list[dict], lang: str, L: dict) -> str:
    rows = []
    for r in sens:
        ref = (r.get("reference") or {}).get("breakeven_users_sustainable")
        lo = (r.get("minus20") or {}).get("breakeven_users_sustainable")
        hi = (r.get("plus20") or {}).get("breakeven_users_sustainable")
        if ref is None:
            continue
        rows.append((LEVER_NAMES.get(r["lever"], r["lever"].replace("_", " ").capitalize()), ref, lo, hi))
    if not rows:
        return ""
    rows.sort(key=lambda t: max(abs((t[2] or t[1]) - t[1]), abs((t[3] or t[1]) - t[1])), reverse=True)
    maxd = max(max(abs((r[2] or r[1]) - r[1]), abs((r[3] or r[1]) - r[1])) for r in rows) or 1
    W, LBL, PADR = 720, 170, 70
    row_h, bar_h = 34, 11
    H = 20 + row_h * len(rows) + 10
    cx = LBL + (W - LBL - PADR) / 2
    scale = (W - LBL - PADR) / 2 / maxd
    parts = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="{esc(L["chart_sens"])}">']
    parts.append(f'<line x1="{cx:.1f}" x2="{cx:.1f}" y1="12" y2="{H - 8}" class="zero"/>')
    ref0 = rows[0][1]
    parts.append(svg_text(cx, 10, fmt_num(round(ref0), lang), "axis", "middle"))
    for k, (name, ref, lo, hi) in enumerate(rows):
        top = 20 + k * row_h
        parts.append(svg_text(LBL - 10, top + row_h / 2 + 4, name, "row-label", "end"))
        for j, (val, sign_label) in enumerate(((lo, "−20 %"), (hi, "+20 %"))):
            by = top + 4 + j * (bar_h + 3)
            parts.append(svg_text(LBL - 10, by + bar_h - 2, "", "axis", "end"))
            if val is None:
                parts.append(svg_text(cx + 6, by + bar_h - 2, f"{sign_label}: ∞", "axis"))
                continue
            d = val - ref
            w = abs(d) * scale
            cls = "better" if d < 0 else "worse"
            x0 = cx - w if d < 0 else cx
            parts.append(f'<rect x="{x0:.1f}" y="{by}" width="{max(w, 1):.1f}" height="{bar_h}" rx="2" class="bar {cls}"><title>{esc(name)} {sign_label}: {fmt_num(round(val), lang)}</title></rect>')
            tx = (cx + 6, "start") if w < 4 else (x0 - 5, "end") if d < 0 else (cx + w + 5, "start")
            parts.append(svg_text(tx[0], by + bar_h - 2, f"{sign_label}: {fmt_num(round(val), lang)}", "axis", tx[1]))
    parts.append("</svg>")
    legend = (f'<span class="lg"><i class="sw better"></i>{esc(L["sens_better"])}</span>'
              f'<span class="lg"><i class="sw worse"></i>{esc(L["sens_worse"])}</span>')
    return f'<figure class="chart tornado" data-kind="bar"><div class="legend">{legend}</div>{"".join(parts)}</figure>'


