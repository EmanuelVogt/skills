# ---------------------------------------------------------------- formatting

def fmt_num(x, lang: str, digits: int = 0) -> str:
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return "—"
    s = f"{x:,.{digits}f}"
    if lang == "pt":
        s = s.translate(str.maketrans(",.", ".,"))
    return s


def fmt_money(x, cur: str, lang: str) -> str:
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return "—"
    sym = CURRENCY_SYMBOL.get(cur, cur + " ")
    return f"{sym} {fmt_num(round(x), lang)}"


def fmt_compact(x: float, cur: str | None = None) -> str:
    sign = "-" if x < 0 else ""
    a = abs(x)
    if a >= 1e9:
        s = f"{a / 1e9:.1f}B"
    elif a >= 1e6:
        s = f"{a / 1e6:.1f}M"
    elif a >= 1e3:
        s = f"{a / 1e3:.0f}k" if a >= 1e4 else f"{a / 1e3:.1f}k"
    else:
        s = f"{a:.0f}"
    s = s.replace(".0k", "k").replace(".0M", "M").replace(".0B", "B")
    sym = (CURRENCY_SYMBOL.get(cur, cur) + " ") if cur else ""
    return f"{sign}{sym}{s}"


def fmt_month(m, L: dict) -> str:
    if m is None:
        return L["never"]
    return L["month"].format(m=int(m))


def fmt_pct(x, lang: str, digits: int = 0) -> str:
    if x is None:
        return "—"
    return fmt_num(x * 100, lang, digits) + " %"


def nice_ticks(lo: float, hi: float, n: int = 5) -> list[float]:
    if hi <= lo:
        hi = lo + 1
    raw = (hi - lo) / n
    mag = 10 ** math.floor(math.log10(raw))
    for mult in (1, 2, 2.5, 5, 10):
        step = mult * mag
        if raw <= step:
            break
    start = math.floor(lo / step) * step
    ticks = []
    v = start
    while v < hi + step * 0.999:
        ticks.append(round(v, 10))
        v += step
    return ticks


# ---------------------------------------------------------------- markdown → html

def esc(s: str) -> str:
    return html.escape(s, quote=False)


def slugify(s: str) -> str:
    s = re.sub(r"[^\w\s-]", "", s.lower(), flags=re.UNICODE)
    return re.sub(r"[\s_-]+", "-", s).strip("-") or "s"


TAG_RE = re.compile(
    r"\[(data|benchmark|estimate|guess|fact|belief|assumption|unknown|blocker|major|minor)"
    r"(?::\s*([^\]]*))?\]",
    re.IGNORECASE,
)
SRC_RE = re.compile(r"\[S(\d+)\]")
SRC_INLINE_RE = re.compile(r"(?<![\w#])S(\d{1,3})(?![\w])")


def render_tags(s: str) -> str:
    def tag(m: re.Match) -> str:
        kind = m.group(1).lower()
        detail = m.group(2)
        body = kind.upper() if kind in ("blocker", "major", "minor") else kind
        if detail:
            detail = SRC_INLINE_RE.sub(r'<a class="src" href="#S\1">S\1</a>', esc(detail))
            return f'<span class="tag tag-{kind}">{body}<span class="tag-detail">{detail}</span></span>'
        return f'<span class="tag tag-{kind}">{body}</span>'

    s = TAG_RE.sub(tag, s)
    s = SRC_RE.sub(r'<a class="src" href="#S\1">[S\1]</a>', s)
    return s


def inline(text: str) -> str:
    codes: list[str] = []

    def stash(m: re.Match) -> str:
        codes.append(f"<code>{esc(m.group(1))}</code>")
        return f"\x01{len(codes) - 1}\x02"

    text = re.sub(r"`([^`\n]+)`", stash, text)
    text = esc(text)
    text = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)\)", r'<img alt="\1" src="\2">', text)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', text)
    text = re.sub(r"&lt;(https?://[^&\s]+)&gt;", r'<a href="\1">\1</a>', text)
    text = re.sub(r"(?<![\"'>=])(https?://[^\s<)\]]+)", r'<a href="\1">\1</a>', text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"__(.+?)__", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    text = re.sub(r"(?<![\w])_(?!\s)([^_]+?)(?<!\s)_(?![\w])", r"<em>\1</em>", text)
    text = re.sub(r"~~(.+?)~~", r"<del>\1</del>", text)
    text = render_tags(text)
    text = text.replace("  \n", "<br>\n")
    return re.sub(r"\x01(\d+)\x02", lambda m: codes[int(m.group(1))], text)


HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
FENCE_RE = re.compile(r"^(```|~~~)\s*(\w+)?\s*$")
HR_RE = re.compile(r"^\s*([-*_])(\s*\1){2,}\s*$")
LIST_RE = re.compile(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$")
TABLE_SEP_RE = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
QUOTE_RE = re.compile(r"^\s{0,3}>\s?(.*)$")


def split_row(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|") and not line.endswith("\\|"):
        line = line[:-1]
    cells = re.split(r"(?<!\\)\|", line)
    return [c.strip().replace("\\|", "|") for c in cells]


def render_table(rows: list[str]) -> str:
    header = split_row(rows[0])
    aligns = []
    for c in split_row(rows[1]):
        left, right = c.startswith(":"), c.endswith(":")
        aligns.append("center" if left and right else "right" if right else "left")
    out = ['<div class="table-wrap"><table>', "<thead><tr>"]
    for i, c in enumerate(header):
        a = aligns[i] if i < len(aligns) else "left"
        out.append(f'<th class="al-{a}">{inline(c)}</th>')
    out.append("</tr></thead><tbody>")
    for r in rows[2:]:
        cells = split_row(r)
        out.append("<tr>")
        for i in range(len(header)):
            c = cells[i] if i < len(cells) else ""
            a = aligns[i] if i < len(aligns) else "left"
            out.append(f'<td class="al-{a}">{inline(c)}</td>')
        out.append("</tr>")
    out.append("</tbody></table></div>")
    return "".join(out)


def render_list(block: list[str], shift: int, prefix: str) -> str:
    first = LIST_RE.match(block[0])
    base_indent = len(first.group(1))
    ordered = first.group(2)[0].isdigit()
    items: list[list[str]] = []
    for line in block:
        m = LIST_RE.match(line)
        if m and len(m.group(1)) <= base_indent:
            items.append([m.group(3)])
        elif items:
            items[-1].append(line)
    out = ["<ol>" if ordered else "<ul>"]
    for it in items:
        head, rest = it[0], it[1:]
        while rest and not rest[-1].strip():
            rest.pop()
        if rest:
            strip = min(len(l) - len(l.lstrip()) for l in rest if l.strip())
            body = [l[strip:] if l.strip() else "" for l in rest]
            if any(LIST_RE.match(l) or not l.strip() for l in body):
                out.append(f"<li>{inline(head)}{md_to_html(chr(10).join(body), shift, prefix)}</li>")
            else:
                out.append(f"<li>{inline(head + ' ' + ' '.join(l.strip() for l in body))}</li>")
        else:
            out.append(f"<li>{inline(head)}</li>")
    out.append("</ol>" if ordered else "</ul>")
    return "".join(out)


def md_to_html(text: str, shift: int = 0, prefix: str = "") -> str:
    lines = text.replace("\r\n", "\n").split("\n")
    out: list[str] = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        fence = FENCE_RE.match(line)
        if fence:
            marker, lang = fence.group(1), fence.group(2)
            j = i + 1
            code = []
            while j < n and not lines[j].startswith(marker):
                code.append(lines[j])
                j += 1
            cls = f' class="lang-{lang}"' if lang else ""
            out.append(f"<pre><code{cls}>{esc(chr(10).join(code))}</code></pre>")
            i = j + 1
            continue
        h = HEADING_RE.match(line)
        if h:
            level = min(6, len(h.group(1)) + shift)
            title = h.group(2)
            hid = f"{prefix}-{slugify(title)}" if prefix else slugify(title)
            out.append(f'<h{level} id="{hid}">{inline(title)}</h{level}>')
            i += 1
            continue
        if HR_RE.match(line):
            out.append("<hr>")
            i += 1
            continue
        if "|" in line and i + 1 < n and TABLE_SEP_RE.match(lines[i + 1]) and "|" in lines[i + 1]:
            j = i
            rows = []
            while j < n and lines[j].strip() and "|" in lines[j]:
                rows.append(lines[j])
                j += 1
            out.append(render_table(rows))
            i = j
            continue
        if QUOTE_RE.match(line):
            j = i
            quote = []
            while j < n and lines[j].strip() and (QUOTE_RE.match(lines[j]) or quote):
                q = QUOTE_RE.match(lines[j])
                quote.append(q.group(1) if q else lines[j])
                j += 1
                if j < n and not lines[j].strip():
                    break
            out.append(f"<blockquote>{md_to_html(chr(10).join(quote), shift, prefix)}</blockquote>")
            i = j
            continue
        if LIST_RE.match(line):
            j = i
            block = []
            while j < n:
                cur = lines[j]
                if not cur.strip():
                    nxt = lines[j + 1] if j + 1 < n else ""
                    if nxt.strip() and (LIST_RE.match(nxt) or nxt.startswith("  ")):
                        block.append(cur)
                        j += 1
                        continue
                    break
                if LIST_RE.match(cur) or cur.startswith("  ") or cur.startswith("\t") or (block and not LIST_RE.match(cur) and not HEADING_RE.match(cur) and not block[-1].strip() == ""):
                    block.append(cur)
                    j += 1
                    continue
                break
            out.append(render_list(block, shift, prefix))
            i = j
            continue
        j = i
        para = []
        while j < n and lines[j].strip() and not (
            HEADING_RE.match(lines[j]) or FENCE_RE.match(lines[j]) or HR_RE.match(lines[j])
            or QUOTE_RE.match(lines[j]) or LIST_RE.match(lines[j])
            or ("|" in lines[j] and j + 1 < n and TABLE_SEP_RE.match(lines[j + 1]))
        ):
            para.append(lines[j])
            j += 1
        if not para:
            para.append(line)
            j = i + 1
        out.append(f"<p>{inline(chr(10).join(para))}</p>")
        i = j
    return "\n".join(out)


