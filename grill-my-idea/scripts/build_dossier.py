def numbers_section(model: dict | None, pivots: list[tuple[str, dict]], L: dict, lang: str) -> str:
    if not model:
        return f'<section id="numbers"><h2>{esc(L["numbers"])}</h2><p class="callout warn">{esc(L["no_model"])}</p></section>'
    cur = model.get("currency", "BRL")
    horizon = int(model.get("horizon_months", 36))
    scs = {k: scenario_summary(model["scenarios"][k]) for k in SCENARIOS if k in model.get("scenarios", {})}
    out = [f'<section id="numbers"><h2>{esc(L["numbers"])}</h2>']

    out.append('<div class="cards">')
    for name in SCENARIOS:
        if name not in scs:
            continue
        s = scs[name]
        rows = []
        if s["goal_target"]:
            rows.append((L["founder_goal"].format(target=fmt_money(s["goal_target"], cur, lang)), fmt_month(s["goal"], L), True))
        rows.append((L["be_users"], fmt_num(None if s["be_users"] is None else math.ceil(s["be_users"]), lang), True))
        rows.append((L["first_profit"], fmt_month(s["first_profit"], L), False))
        rows.append((L["peak_cash"], fmt_money(s["peak_cash"], cur, lang), False))
        rows.append((L["users_at"].format(m=12), fmt_num(None if s["users_m12"] is None else round(s["users_m12"]), lang), False))
        rows.append((L["users_at"].format(m=horizon), fmt_num(None if s["users_end"] is None else round(s["users_end"]), lang), False))
        rows.append((L["mrr_at"].format(m=horizon), fmt_money(s["mrr_end"], cur, lang), False))
        rows.append((L["ltv_cac"], fmt_num(s["ltv_cac"], lang, 1) + "×" if s["ltv_cac"] is not None else "∞", False))
        rows.append((L["payback"], L["months"].format(m=fmt_num(s["payback"], lang, 1)) if s["payback"] is not None else "∞", False))
        cls = "card realistic" if name == "realistic" else "card"
        out.append(f'<article class="{cls}"><h3><i class="sw s{SERIES_SLOT[name]}"></i>{esc(L[name])}</h3><dl>')
        for label, value, big in rows:
            out.append(f'<div class="{"kv big" if big else "kv"}"><dt>{esc(label)}</dt><dd>{esc(value)}</dd></div>')
        out.append("</dl></article>")
    out.append("</div>")

    series_users, series_cash = [], []
    for name in SCENARIOS:
        if name not in scs:
            continue
        rows = scs[name]["rows"]
        series_users.append({"label": L[name], "slot": SERIES_SLOT[name], "values": [r.get("users") for r in rows]})
        series_cash.append({"label": L[name], "slot": SERIES_SLOT[name], "values": [r.get("cumulative_cash") for r in rows]})
    be_ref = scs.get("realistic", {}).get("be_users")
    out.append('<div class="charts">')
    out.append(f'<div class="chart-block"><h3>{esc(L["chart_users"])}</h3>')
    out.append(line_chart("chart-users", series_users, horizon, None, L, lang, (be_ref, L["break_even_ref"]) if be_ref else None))
    out.append(checkpoint_table(series_users, horizon, None, lang, L))
    out.append("</div>")
    out.append(f'<div class="chart-block"><h3>{esc(L["chart_cash"])}</h3>')
    out.append(line_chart("chart-cash", series_cash, horizon, cur, L, lang))
    out.append(checkpoint_table(series_cash, horizon, cur, lang, L))
    out.append("</div></div>")

    mk = model.get("market")
    if mk and (mk.get("tam_users") or mk.get("sam_users")):
        out.append(f'<h3>{esc(L["market_title"])}</h3><div class="market">')
        be = scs.get("realistic", {}).get("be_users")
        for key, label in (("tam", L["tam"]), ("sam", L["sam"]), ("som", L["som"])):
            users = mk.get("som_users_year3") if key == "som" else mk.get(f"{key}_users")
            rev = mk.get(f"{key}_annual_revenue")
            if not users:
                continue
            extra = ""
            if key == "sam" and be and users:
                extra = f'<small>break-even = {fmt_pct(be / users, lang, 1)} {esc(L["of_sam"])}</small>'
            if key == "som" and mk.get("som_share_year3"):
                extra = f'<small>{fmt_pct(mk["som_share_year3"], lang, 1)} {esc(L["of_sam"])}</small>'
            out.append(f'<div class="tile {key}"><span class="tile-label">{esc(label)}</span>'
                       f'<span class="tile-value">{fmt_num(round(users), lang)}</span><span class="tile-sub">{esc(L["customers"])}</span>'
                       f'<span class="tile-value2">{fmt_money(rev, cur, lang)}</span><span class="tile-sub">{esc(L["annual_revenue"])}</span>{extra}</div>')
        out.append("</div>")

    sens = model.get("sensitivity") or []
    t = tornado(sens, lang, L)
    if t:
        out.append(f'<div class="chart-block"><h3>{esc(L["chart_sens"])}</h3>{t}</div>')

    if pivots:
        out.append(f'<h3>{esc(L["pivots"])}</h3><div class="table-wrap"><table><thead><tr>'
                   f'<th>{esc(L["pivot"])}</th><th class="al-right">{esc(L["be_users"])}</th>'
                   f'<th class="al-right">{esc(L["first_profit"])}</th><th class="al-right">{esc(L["peak_cash"])}</th>'
                   f'<th class="al-right">{esc(L["users_at"].format(m=horizon))}</th></tr></thead><tbody>')
        base = scs.get("realistic")
        if base:
            out.append(f'<tr><td><em>{esc(L["realistic"])}</em></td><td class="al-right">{fmt_num(None if base["be_users"] is None else math.ceil(base["be_users"]), lang)}</td>'
                       f'<td class="al-right">{fmt_month(base["first_profit"], L)}</td><td class="al-right">{fmt_money(base["peak_cash"], cur, lang)}</td>'
                       f'<td class="al-right">{fmt_num(None if base["users_end"] is None else round(base["users_end"]), lang)}</td></tr>')
        for pname, pm in pivots:
            ps = scenario_summary(pm["scenarios"]["realistic"])
            pcur = pm.get("currency", cur)
            out.append(f'<tr><td>{esc(pname)}</td><td class="al-right">{fmt_num(None if ps["be_users"] is None else math.ceil(ps["be_users"]), lang)}</td>'
                       f'<td class="al-right">{fmt_month(ps["first_profit"], L)}</td><td class="al-right">{fmt_money(ps["peak_cash"], pcur, lang)}</td>'
                       f'<td class="al-right">{fmt_num(None if ps["users_end"] is None else round(ps["users_end"]), lang)}</td></tr>')
        out.append("</tbody></table></div>")

    if model.get("warnings"):
        out.append(f'<div class="callout warn"><strong>{esc(L["warnings"])}</strong><ul>')
        out += [f"<li>{inline(w)}</li>" for w in model["warnings"]]
        out.append("</ul></div>")
    out.append("</section>")
    return "".join(out)


def sources_section(md: str | None, L: dict) -> str:
    if not md:
        return ""
    _, body = split_title(md)
    out = md_to_html(body, 1, "sources")
    ref = r'(?:<a class="src" href="#S\d+">)?\[?S(\d+)\]?(?:</a>)?'
    out = re.sub(rf'<td class="al-(\w+)">{ref}</td>', r'<td class="al-\1" id="S\2">S\2</td>', out)
    out = re.sub(rf'<li>{ref}(\s*[:—–-]?\s*)', r'<li id="S\1">S\1\2', out)
    return f'<section id="sources"><h2>{esc(L["sources"])}</h2>{out}</section>'


def research_section(dossier: str, L: dict) -> str:
    files = sorted(glob.glob(os.path.join(dossier, "work", "research", "*.md")) or glob.glob(os.path.join(dossier, "research", "*.md")))
    if not files:
        return ""
    files.sort(key=lambda p: (0 if os.path.basename(p) == "summary.md" else 1, p))
    out = [f'<section id="research"><h2>{esc(L["research"])}</h2>']
    for p in files:
        with open(p, encoding="utf-8") as f:
            md = f.read()
        title, body = split_title(md)
        base = os.path.splitext(os.path.basename(p))[0]
        out.append(f'<details class="research"><summary>{esc(title or base)}</summary>{md_to_html(body, 2, "research-" + base)}</details>')
    out.append("</section>")
    return "".join(out)


