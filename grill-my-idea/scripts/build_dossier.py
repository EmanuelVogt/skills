def build(dossier: str, out_path: str, lang: str, include_research: bool) -> None:
    L = LABELS[lang]
    readme = read_text(dossier, "README.md")
    if readme is None:
        fail(f"README.md not found in {dossier}")
    r = parse_readme(readme)
    model = read_json(os.path.join(dossier, "work", "model_output.json")) or read_json(os.path.join(dossier, "model_output.json"))
    pivots = []
    for p in sorted(glob.glob(os.path.join(dossier, "work", "model-pivot-*_output.json")) + glob.glob(os.path.join(dossier, "model-pivot-*_output.json"))):
        name = re.sub(r"^model-pivot-|_output\.json$", "", os.path.basename(p)).replace("-", " ")
        pm = read_json(p)
        if pm and "scenarios" in pm:
            pivots.append((name, pm))

    sections: list[tuple[str, str, str]] = []
    missing: list[str] = []
    for fname, sid in SECTIONS:
        md = read_text(dossier, fname)
        if md is None:
            missing.append(fname)
            continue
        title, body = split_title(md)
        label = L[sid]
        inner = md_to_html(body, 1, sid)
        if sid in COLLAPSED_SECTIONS:
            inner = f'<details class="section-body"><summary>{esc(title or label)}</summary>{inner}</details>'
        sections.append((sid, label, f'<section id="{sid}"><h2>{esc(label)}</h2>{inner}</section>'))

    verdict = r["verdict"]
    vcls, vic = VERDICT_STYLE.get(verdict, ("", "•"))
    verdict_html = (f'<div class="verdict {vcls}"><span class="ic">{vic}</span>{esc(L["verdict"])}: {esc(verdict)}</div>'
                    if verdict else "")
    meta_html = "".join(f"<li>{inline(m)}</li>" for m in r["meta"])
    quote_html = f"<blockquote>{md_to_html(r['quote'])}</blockquote>" if r["quote"] else ""

    nav = [f'<a href="#numbers">{esc(L["numbers"])}</a>', f'<a href="#summary">{esc(L["summary"])}</a>']
    nav += [f'<a href="#{sid}">{esc(label)}</a>' for sid, label, _ in sections]
    sources = sources_section(read_text(dossier, "sources.md"), L)
    if sources:
        nav.append(f'<a href="#sources">{esc(L["sources"])}</a>')
    research = research_section(dossier, L) if include_research else ""
    if research:
        nav.append(f'<a href="#research">{esc(L["research"])}</a>')

    summary_html = f'<section id="summary"><h2>{esc(L["summary"])}</h2>{md_to_html(r["body"], 1, "summary")}</section>'
    title = f"{r['name']} — {verdict}" if verdict else r["name"]

    doc = f"""<!doctype html>
<html lang="{'pt-BR' if lang == 'pt' else 'en'}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<style>{CSS}</style>
</head>
<body>
<div class="layout">
<nav class="toc"><div class="brand">{esc(L["menu"])}</div>{"".join(nav)}<div class="print">{esc(L["print"])}: Ctrl/Cmd + P</div></nav>
<main>
<header class="hero">
{verdict_html}
<h1 class="name">{inline(r["name"])}</h1>
<ul class="meta">{meta_html}</ul>
{quote_html}
<p class="built">{esc(L["verdict_meta"].format(date=date.today().isoformat()))}</p>
</header>
{numbers_section(model, pivots, L, lang)}
{summary_html}
{"".join(s[2] for s in sections)}
{sources}
{research}
<footer>{esc(L["footer"])}</footer>
</main>
</div>
<script>{JS}</script>
</body>
</html>
"""
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(doc)
    size_kb = os.path.getsize(out_path) / 1024
    print(f"wrote {out_path} ({size_kb:.0f} KB)")
    if model is None:
        print("warning: " + L["no_model"], file=sys.stderr)
    for m in missing:
        print("warning: " + L["missing"].format(name=m), file=sys.stderr)


def main() -> None:
    ap = argparse.ArgumentParser(description="compile an ideas/<slug>/ dossier into one dossier.html")
    ap.add_argument("dossier", help="path to ideas/<slug>/")
    ap.add_argument("--out", help="output path (default: <dossier>/dossier.html)")
    ap.add_argument("--lang", choices=["en", "pt"], default="en", help="language of the page chrome (labels, cards)")
    ap.add_argument("--no-research", action="store_true", help="leave the raw research notes out of the HTML")
    args = ap.parse_args()
    dossier = args.dossier.rstrip("/")
    if not os.path.isdir(dossier):
        fail(f"not a directory: {dossier}")
    out = args.out or os.path.join(dossier, "dossier.html")
    build(dossier, out, args.lang, not args.no_research)


if __name__ == "__main__":
    main()
